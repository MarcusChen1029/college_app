// Parity check between public.activities_v2() (supabase/migrations/0038_activities_v2.sql) and upgradeActivities()
// (web/lib/activities.ts), using the shared fixtures web/lib/fixtures/activities-v1.json -> activities-v2.json.
//
//   node scripts/check_activities_sql.mjs --generate [out.sql]
//     Writes supabase/patches/2026-10-28-activities-v2-parity.sql (or out.sql): the function copied verbatim from the
//     migration (between its BEGIN/END markers) into pg_temp, then one SELECT returning one row (k, v2) per fixture
//     student. Run it in ONE execute_sql call (pg_temp lives for the session). Also checks that the migration's
//     program list and old type map equal the ones in activities.ts.
//
//   node scripts/check_activities_sql.mjs <results.json>
//     Compares the rows the query returned (a JSON array of {k, v2}; the MCP's wrapper text around it is ignored,
//     v2 may be an object or a JSON string) with activities-v2.json, with jsonb semantics: key order does not
//     matter, null and a missing key differ. Exit 0 when every student matches, 1 with a readable diff otherwise.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const MIGRATION = resolve(ROOT, "supabase/migrations/0038_activities_v2.sql");
const V1 = resolve(ROOT, "web/lib/fixtures/activities-v1.json");
const V2 = resolve(ROOT, "web/lib/fixtures/activities-v2.json");
const ACTIVITIES_TS = resolve(ROOT, "web/lib/activities.ts");
const PATCH = resolve(ROOT, "supabase/patches/2026-10-28-activities-v2-parity.sql");

const BEGIN = "-- BEGIN activities_v2";
const END = "-- END activities_v2";
const HEAD = "create or replace function public.activities_v2(";

/** The CREATE FUNCTION statement between the markers, exactly as in the migration. */
export function functionSql(migration) {
  const start = migration.indexOf(BEGIN);
  const end = migration.indexOf(END);
  if (start < 0 || end < start) throw new Error(`markers "${BEGIN}" / "${END}" not found in the migration`);
  const body = migration.slice(start + BEGIN.length, end).trim();
  if (!body.startsWith(HEAD)) throw new Error(`the function between the markers must start with "${HEAD}"`);
  if (body.indexOf("public.activities_v2", HEAD.length) >= 0) throw new Error("the function refers to public.activities_v2 inside its body");
  return body;
}

const sqlString = (s) => `'${s.replace(/'/g, "''")}'`;

/** The parity patch: the function in pg_temp, then one row (k, v2) per v1 fixture student. */
export function parityPatch(migration, v1Fixture) {
  const fn = functionSql(migration).replace(HEAD, "create or replace function pg_temp.activities_v2(");
  const rows = v1Fixture.map((s, i) => `  (${i + 1}, ${sqlString(s.student)}, ${sqlString(JSON.stringify(s.activities))}::jsonb)`);
  return [
    "-- GENERATED by `node scripts/check_activities_sql.mjs --generate`; do not edit (edit the migration and regenerate).",
    "-- Parity check for public.activities_v2 (migration 0038) against web/lib/fixtures/activities-v1.json -> activities-v2.json.",
    "-- Run the WHOLE file in ONE execute_sql call (pg_temp is per session; nothing is written to the database), save the",
    "-- returned rows as JSON, then: node scripts/check_activities_sql.mjs <results.json>  (exit 0 = parity).",
    "",
    fn,
    "",
    "select t.k, pg_temp.activities_v2(t.v1) as v2",
    "from (values",
    rows.join(",\n"),
    ") as t(n, k, v1)",
    "order by t.n;",
    "",
  ].join("\n");
}

/** Checks the migration's embedded lists against activities.ts; returns problems (empty = fine). */
export async function listProblems(migration) {
  const problems = [];
  const { UC_EDPREP_PROGRAMS } = await import(pathToFileURL(ACTIVITIES_TS).href);
  const block = /k_programs constant text\[\] := array\[([\s\S]*?)\n  \];/.exec(migration);
  const sqlPrograms = block ? [...block[1].matchAll(/\['([^']*)', '([^']*)'\]/g)].map((m) => ({ value: m[1], label: m[2] })) : [];
  if (JSON.stringify(sqlPrograms) !== JSON.stringify(UC_EDPREP_PROGRAMS.map(({ value, label }) => ({ value, label })))) {
    problems.push("k_programs in the migration differs from UC_EDPREP_PROGRAMS in web/lib/activities.ts");
  }
  const ts = readFileSync(ACTIVITIES_TS, "utf8");
  const tsBlock = /const OLD_CA_TYPES = new Map<string, string>\(\[([\s\S]*?)\]\);/.exec(ts);
  const tsTypes = tsBlock ? Object.fromEntries([...tsBlock[1].matchAll(/\["([^"]+)", "([^"]+)"\]/g)].map((m) => [m[1], m[2]])) : {};
  const sqlBlock = /k_old_types constant jsonb := '([\s\S]*?)';/.exec(migration);
  const sqlTypes = sqlBlock ? JSON.parse(sqlBlock[1]) : {};
  if (Object.keys(tsTypes).length === 0 || JSON.stringify(sortKeys(sqlTypes)) !== JSON.stringify(sortKeys(tsTypes))) {
    problems.push("k_old_types in the migration differs from OLD_CA_TYPES in web/lib/activities.ts");
  }
  return problems;
}

const sortKeys = (o) => Object.fromEntries(Object.keys(o).sort().map((k) => [k, o[k]]));

/** The {k, v2} rows from a results file; tolerates text around the JSON array (the MCP wraps its output). */
export function parseResults(text) {
  let data;
  try {
    data = JSON.parse(text);
  } catch {
    const start = text.indexOf("[");
    const end = text.lastIndexOf("]");
    if (start < 0 || end < start) throw new Error("no JSON array found in the results file");
    data = JSON.parse(text.slice(start, end + 1));
  }
  if (!Array.isArray(data)) throw new Error("the results must be a JSON array of {k, v2}");
  return data.map((row, i) => {
    if (typeof row !== "object" || row === null || typeof row.k !== "string") throw new Error(`row ${i} has no string "k"`);
    return { k: row.k, v2: typeof row.v2 === "string" ? JSON.parse(row.v2) : row.v2 };
  });
}

const isObject = (v) => typeof v === "object" && v !== null && !Array.isArray(v);
const show = (v) => (v === undefined ? "(missing)" : JSON.stringify(v));

/** Differences between two JSON values, jsonb-style (object key order ignored). */
export function jsonDiff(expected, actual, path = "$", out = []) {
  if (Array.isArray(expected) && Array.isArray(actual)) {
    if (expected.length !== actual.length) out.push(`${path}: expected ${expected.length} items, got ${actual.length}`);
    for (let i = 0; i < Math.min(expected.length, actual.length); i++) jsonDiff(expected[i], actual[i], `${path}[${i}]`, out);
  } else if (isObject(expected) && isObject(actual)) {
    for (const key of [...new Set([...Object.keys(expected), ...Object.keys(actual)])].sort()) {
      const p = `${path}.${key}`;
      if (!(key in actual)) out.push(`${p}: missing (expected ${show(expected[key])})`);
      else if (!(key in expected)) out.push(`${p}: unexpected key (got ${show(actual[key])})`);
      else jsonDiff(expected[key], actual[key], p, out);
    }
  } else if (expected !== actual) {
    out.push(`${path}: expected ${show(expected)}, got ${show(actual)}`);
  }
  return out;
}

/** Every difference between the query rows and the v2 fixture; empty = parity. */
export function compare(rows, v2Fixture) {
  const out = [];
  const byKey = new Map();
  for (const row of rows) {
    if (byKey.has(row.k)) out.push(`${row.k}: returned more than once`);
    byKey.set(row.k, row.v2);
  }
  const expectedKeys = new Set(v2Fixture.map((s) => s.student));
  for (const k of byKey.keys()) if (!expectedKeys.has(k)) out.push(`${k}: not a fixture student`);
  for (const s of v2Fixture) {
    if (!byKey.has(s.student)) out.push(`${s.student}: no row returned`);
    else for (const d of jsonDiff(s.activities, byKey.get(s.student))) out.push(`${s.student}: ${d}`);
  }
  return out;
}

const readJson = (p) => JSON.parse(readFileSync(p, "utf8"));

async function main(args) {
  if (args[0] === "--generate") {
    const migration = readFileSync(MIGRATION, "utf8");
    const problems = await listProblems(migration);
    for (const p of problems) console.error(`FAIL: ${p}`);
    if (problems.length) return 1;
    const out = args[1] ? resolve(args[1]) : PATCH;
    const v1 = readJson(V1);
    writeFileSync(out, parityPatch(migration, v1));
    console.log(`wrote ${out} (${v1.length} students); program list and old type map match activities.ts`);
    return 0;
  }
  if (args.length !== 1) {
    console.error("usage: node scripts/check_activities_sql.mjs --generate [out.sql] | <results.json>");
    return 2;
  }
  const expected = readJson(V2);
  const diffs = compare(parseResults(readFileSync(resolve(args[0]), "utf8")), expected);
  if (diffs.length === 0) {
    console.log(`parity OK: ${expected.length}/${expected.length} students match activities-v2.json`);
    return 0;
  }
  const shown = diffs.slice(0, 60);
  console.error(`parity FAILED: ${diffs.length} difference(s)`);
  for (const d of shown) console.error(`  ${d}`);
  if (diffs.length > shown.length) console.error(`  ... and ${diffs.length - shown.length} more`);
  return 1;
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  main(process.argv.slice(2)).then(
    (code) => process.exit(code),
    (err) => {
      console.error(`error: ${err.message}`);
      process.exit(2);
    },
  );
}
