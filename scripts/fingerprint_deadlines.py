#!/usr/bin/env python3
"""Print one read-only SQL query that checks the live deadline rows of some colleges against the expected rows.

The query embeds (id, md5) VALUES of the expected rows and returns only the problems among those colleges' deadlines
(missing / extra / mismatch, by id), then one final count row. Python and SQL hash the same canonical text:
  concat_ws('|', id::text, kind, coalesce(plan_key,''), coalesce(label,''), coalesce(due_date::text,''),
            coalesce(notes,''), coalesce(intake,''), coalesce(program_id::text,''), coalesce(source_id::text,''))
Text and dates only (no booleans, arrays or numerics, whose text forms differ between Python and Postgres).

Usage: python -I scripts/fingerprint_deadlines.py (--only slug,slug | --from-json <baseline.json>) [--pre-migration] [--out file]
  --only           expected rows = what scripts/build_seed.py builds from data/ now (college rows + course rows)
  --from-json      expected rows = a --dump-deadlines baseline (what should be live before the patch)
  --pre-migration  leave intake and program_id out of the hash (the live table has no such columns before the migration)
"""
import hashlib, importlib.util, json, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
COLS = ["kind", "plan_key", "label", "due_date", "notes", "intake", "program_id", "source_id"]
SQL_PART = {"kind": "d.kind", "plan_key": "coalesce(d.plan_key,'')", "label": "coalesce(d.label,'')",
            "due_date": "coalesce(d.due_date::text,'')", "notes": "coalesce(d.notes,'')", "intake": "coalesce(d.intake,'')",
            "program_id": "coalesce(d.program_id::text,'')", "source_id": "coalesce(d.source_id::text,'')"}


def cols(pre_migration=False):
    return [k for k in COLS if not (pre_migration and k in ("intake", "program_id"))]


def canonical(row, pre_migration=False):
    """The text the SQL side builds for one row; None is ''."""
    return "|".join([row["id"]] + [row.get(k) or "" for k in cols(pre_migration)])


def md5(row, pre_migration=False):
    return hashlib.md5(canonical(row, pre_migration).encode("utf-8")).hexdigest()


def lit(s):
    return "'" + str(s).replace("'", "''") + "'"


def query(rows, slugs, pre_migration=False, note=""):
    """The check query for these expected rows, scoped to the deadlines of these colleges (by slug)."""
    if rows:
        expected = "values\n " + ",\n ".join(f"({lit(r['id'])}::uuid, {lit(md5(r, pre_migration))})" for r in rows)
    else:
        expected = "select null::uuid, null::text where false"
    text = "concat_ws('|', d.id::text, " + ", ".join(SQL_PART[k] for k in cols(pre_migration)) + ")"
    variant = "pre-migration variant (7 fields, the table before the migration)" if pre_migration else "all 9 fields"
    return f"""-- GENERATED by scripts/fingerprint_deadlines.py{note}; {variant}. Read-only.
-- Returns only problem rows (missing = expected but not live, extra = live but not expected, mismatch = different
-- content), then one 'total' row with the counts. Every row but 'total' is a problem.
with expected (id, md5) as ({expected}),
live as (
  select d.id, md5({text}) as md5
  from public.deadlines d
  join public.institutions i on i.id = d.institution_id
  where i.slug in ({', '.join(lit(s) for s in slugs)})
),
problems as (
  select coalesce(e.id, l.id) as id,
         case when l.id is null then 'missing' when e.id is null then 'extra' else 'mismatch' end as problem
  from expected e full join live l on l.id = e.id
  where l.id is null or e.id is null or l.md5 <> e.md5
)
select id, problem from (
  select id::text as id, problem, 0 as ord from problems
  union all
  select 'total', format('%s live rows, %s expected, %s problems',
                         (select count(*) from live), (select count(*) from expected), (select count(*) from problems)), 1
) r
order by ord, id;
"""


def rows_from_json(path):
    with open(path, encoding="utf-8") as f:
        doc = json.load(f)
    return doc["deadlines"], doc["slugs"]


def rows_from_data(slugs):
    spec = importlib.util.spec_from_file_location("build_seed", os.path.join(ROOT, "scripts/build_seed.py"))
    bs = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(bs)
    col = {}
    bs.build(slugs, insert_only=True, collect=col)
    if bs.errors:
        sys.exit("Validation errors:\n  " + "\n  ".join(bs.errors))
    return col["deadlines"], col["slugs"]


def arg(name):
    return sys.argv[sys.argv.index(name) + 1] if name in sys.argv else None


if __name__ == "__main__":
    only, src = arg("--only"), arg("--from-json")
    if bool(only) == bool(src):
        sys.exit("give exactly one of --only <slugs> or --from-json <baseline.json>")
    pre = "--pre-migration" in sys.argv
    rows, slugs = rows_from_json(src) if src else rows_from_data(only.split(","))
    note = f" --from-json {os.path.basename(src)}" if src else " --only (data/ now)"
    sql = query(rows, slugs, pre, note + (" --pre-migration" if pre else ""))
    out = arg("--out")
    if out:
        with open(out, "w", encoding="utf-8", newline="\n") as f:
            f.write(sql)
        print(f"wrote {out} ({len(rows)} expected rows, {len(slugs)} colleges)")
    else:
        sys.stdout.write(sql)
