#!/usr/bin/env python3
"""Generate web/lib/interest-careers.ts from official sources (no hand-typed numbers).

Sources:
  * O*NET 31.0 Database text files (CC BY 4.0), https://www.onetcenter.org/database.html
    - Occupation Data.txt, Job Zones.txt, Career Interest Types.txt (scale OI = the six RIASEC scores, 1-7)
  * NCES CIP 2020 to SOC 2018 crosswalk (US government publication),
    https://nces.ed.gov/ipeds/cipcode/Files/CIP2020_SOC2018_Crosswalk.xlsx  (sheet SOC-CIP)

Usage:
  python3 -I scripts/build_interest_careers.py --onet <dir with db_31_0_text files> --cip <crosswalk.xlsx>
Selection rule (deterministic): O*NET-SOC codes ending .00, Job Zone 4 or 5 (typically a bachelor's degree or more),
with at least one CIP program in the crosswalk; per SOC major group keep the 10 with the most linked programs
(ties by code); then keep the best MAX_TOTAL overall (same ordering) so no one field dominates.
"""
import argparse
import json
import re
import zipfile
import xml.etree.ElementTree as ET
from collections import defaultdict
from pathlib import Path

MAX_PER_GROUP = 10
MAX_TOTAL = 110
MAX_PROGRAMS = 4
NS = {"m": "http://schemas.openxmlformats.org/spreadsheetml/2006/main"}
TYPES = ["Realistic", "Investigative", "Artistic", "Social", "Enterprising", "Conventional"]
GROUP_NAMES = {}


def read_tsv(path):
    with open(path, encoding="utf-8") as f:
        header = f.readline().rstrip("\n").split("\t")
        for line in f:
            parts = line.rstrip("\n").split("\t")
            yield dict(zip(header, parts))


def read_soc_cip(xlsx):
    z = zipfile.ZipFile(xlsx)
    ss = ["".join(t.text or "" for t in si.iter("{%s}t" % NS["m"])) for si in ET.fromstring(z.read("xl/sharedStrings.xml")).findall("m:si", NS)]
    wb = z.read("xl/workbook.xml").decode()
    rels = z.read("xl/_rels/workbook.xml.rels").decode()
    rid = re.search(r'<sheet name="SOC-CIP"[^>]*r:id="(rId\d+)"', wb).group(1)
    target = re.search(r'Id="%s"[^>]*Target="([^"]+)"|Target="([^"]+)"[^>]*Id="%s"' % (rid, rid), rels)
    target = target.group(1) or target.group(2)
    root = ET.fromstring(z.read("xl/" + target.lstrip("/").replace("xl/", "")))
    out = defaultdict(list)
    for i, r in enumerate(root.findall(".//m:row", NS)):
        vals = []
        for c in r.findall("m:c", NS):
            v = c.find("m:v", NS)
            if v is not None:
                vals.append(ss[int(v.text)] if c.get("t") == "s" else v.text)
        if i == 0 or len(vals) < 4:
            continue
        soc, _, cip, cip_title = vals[:4]
        out[soc].append((cip, cip_title.rstrip(".")))
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--onet", required=True)
    ap.add_argument("--cip", required=True)
    ap.add_argument("--out", default=str(Path(__file__).resolve().parent.parent / "web" / "lib" / "interest-careers.ts"))
    a = ap.parse_args()
    d = Path(a.onet)

    titles = {r["O*NET-SOC Code"]: r["Title"] for r in read_tsv(d / "Occupation Data.txt")}
    zones = {r["O*NET-SOC Code"]: int(r["Job Zone"]) for r in read_tsv(d / "Job Zones.txt")}
    scores = defaultdict(dict)
    for r in read_tsv(d / "Career Interest Types.txt"):
        if r["Scale ID"] == "OI":
            scores[r["O*NET-SOC Code"]][r["Element Name"]] = float(r["Data Value"])
    soc_cip = read_soc_cip(a.cip)

    cands = []
    for code, s in scores.items():
        if not code.endswith(".00") or len(s) != 6 or zones.get(code, 0) < 4:
            continue
        progs = soc_cip.get(code[:7], [])
        if not progs:
            continue
        cands.append((code, titles[code], zones[code], s, progs))
    cands.sort(key=lambda c: (-len(c[4]), c[0]))
    per_group = defaultdict(int)
    picked = []
    for c in cands:
        g = c[0][:2]
        if per_group[g] >= MAX_PER_GROUP:
            continue
        per_group[g] += 1
        picked.append(c)
    picked = picked[:MAX_TOTAL]
    picked.sort(key=lambda c: c[0])

    rows = []
    for code, title, zone, s, progs in picked:
        # One program per 4-digit CIP series, broad ("General") programs first, then by CIP code.
        seen, names = set(), []
        for cip, t in sorted(progs, key=lambda p: ("General" not in p[1], p[0])):
            if cip[:5] not in seen:
                seen.add(cip[:5])
                names.append(t)
        rows.append({"code": code, "title": title, "zone": zone, "scores": [round(s[t], 2) for t in TYPES], "programs": names[:MAX_PROGRAMS]})

    body = ",\n".join("  " + json.dumps(r, ensure_ascii=False) for r in rows)
    text = (
        "// GENERATED by scripts/build_interest_careers.py. Do not edit by hand.\n"
        "// O*NET 31.0 Database (CC BY 4.0), U.S. Department of Labor, Employment and Training Administration; programs from the\n"
        "// NCES CIP 2020 to SOC 2018 crosswalk. Scores are the six O*NET Occupational Interest values (1-7) in R, I, A, S, E, C order.\n"
        "export type InterestCareer = {\n"
        "  /** O*NET-SOC code, e.g. 15-1252.00 */\n  code: string;\n  title: string;\n  /** O*NET Job Zone, 4 = bachelor's degree typical, 5 = graduate degree often. */\n  zone: number;\n"
        "  /** O*NET occupational interest scores (1-7), order R, I, A, S, E, C. */\n  scores: [number, number, number, number, number, number];\n"
        "  /** College programs (CIP titles) the NCES crosswalk links to this occupation. */\n  programs: string[];\n};\n\n"
        "export const ONET_VERSION = \"31.0\";\n\n"
        "export const INTEREST_CAREERS: InterestCareer[] = [\n" + body + ",\n];\n"
    )
    Path(a.out).write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {len(rows)} occupations to {a.out}")


if __name__ == "__main__":
    main()
